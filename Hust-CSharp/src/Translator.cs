using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace HustCSharp;

/// <summary>
/// Translator for Hust-CSharp
/// Transpiles Hust source code to C#
/// </summary>
public class Translator
{
    private readonly Preprocessor _preprocessor = new();
    private readonly StringBuilder _output = new();
    private int _indentLevel = 0;
    private bool _hasMainMethod = false;
    private int _currentMethodIndent = 0; // Track current method body indentation
    private bool _inMethod = false; // Track if we are inside a method
    private bool _methodStartLine = false; // Track if next line is first line of method body
    
    /// <summary>
    /// Translation result
    /// </summary>
    public class TranslationResult
    {
        public bool Success { get; set; } = true;
        public string Output { get; set; } = string.Empty;
        public List<string> Errors { get; } = new();
        public List<string> Warnings { get; } = new();
    }

    /// <summary>
    /// Translate Hust source to C#
    /// </summary>
    public TranslationResult Translate(string source, string fileName)
    {
        var result = new TranslationResult();
        
        try
        {
            // Step 1: Preprocess (protect strings/comments, check dialect, normalize block structure)
            var (processed, dialect) = _preprocessor.Process(source);
            
            if (!dialect.IsValid)
            {
                result.Success = false;
                result.Errors.AddRange(dialect.Errors);
                return result;
            }
            
            result.Warnings.AddRange(dialect.Warnings);
            
            // Step 2: Parse and translate
            var translated = TranslateSource(processed, dialect.DetectedDialect);
            
            // Step 3: Restore strings and comments
            var restored = _preprocessor.Restore(translated);
            
            // Step 4: Verify no placeholders remain
            if (!_preprocessor.VerifyNoPlaceholders(restored))
            {
                result.Success = false;
                result.Errors.Add("Internal error: placeholders remain in output");
                return result;
            }
            
            result.Output = restored;
        }
        catch (Exception ex)
        {
            result.Success = false;
            result.Errors.Add($"Translation error: {ex.Message}");
        }
        
        return result;
    }

    /// <summary>
    /// Translate source code
    /// </summary>
    private string TranslateSource(string source, Preprocessor.DialectType dialect)
    {
        _output.Clear();
        _hasMainMethod = false;
        
        // Add C# header
        _output.AppendLine("// Generated by Hust-CSharp");
        _output.AppendLine("// Do not edit manually");
        _output.AppendLine("");
        
        // Add using statements based on dialect
        if (dialect == Preprocessor.DialectType.CSharpDialect || dialect == Preprocessor.DialectType.PureHust)
        {
            _output.AppendLine("using System;");
            _output.AppendLine("using System.Collections.Generic;");
            _output.AppendLine("using System.Linq;");
            _output.AppendLine("");
        }
        
        // Start Program class
        _output.AppendLine("public class Program");
        _output.AppendLine("{");
        
        // Parse and translate line by line
        var lines = source.Split('\n');
        
        foreach (var line in lines)
        {
            var trimmed = line.Trim();
            
            // Skip empty lines
            if (string.IsNullOrWhiteSpace(trimmed))
            {
                _output.AppendLine();
                continue;
            }
            
            // Skip comments (already protected)
            if (trimmed.StartsWith("__COMMENT_"))
            {
                _output.AppendLine(line); // Keep original indentation
                continue;
            }
            
            // Translate use statements
            if (trimmed.StartsWith("use "))
            {
                TranslateUseStatement(trimmed);
                continue;
            }
            
            // Translate class declaration
            if (trimmed.StartsWith("class "))
            {
                TranslateClassDeclaration(line); // Pass original line with indentation
                continue;
            }
            
            // Translate method declaration
            if (IsMethodDeclaration(trimmed))
            {
                TranslateMethodDeclaration(line); // Pass original line with indentation
                continue;
            }
            
            // Translate variable declaration
            if (IsVariableDeclaration(trimmed))
            {
                TranslateVariableDeclaration(line); // Pass original line with indentation
                continue;
            }
            
            // Translate control flow
            if (trimmed.StartsWith("if ") || trimmed.StartsWith("if("))
            {
                TranslateIfStatement(line); // Pass original line with indentation
                continue;
            }
            
            if (trimmed.StartsWith("for ") || trimmed.StartsWith("for("))
            {
                TranslateForStatement(line); // Pass original line with indentation
                continue;
            }
            
            if (trimmed.StartsWith("while ") || trimmed.StartsWith("while("))
            {
                TranslateWhileStatement(line); // Pass original line with indentation
                continue;
            }
            
            // Translate return statement
            if (trimmed.StartsWith("return "))
            {
                TranslateReturnStatement(line); // Pass original line with indentation
                continue;
            }
            
            // Default: emit as-is (preprocessor already handled indentation)
            // If inside method, add 4 extra spaces (for class wrapper)
            var outputLine = _inMethod ? "    " + line : line;
            _output.AppendLine(TranslateExpression(outputLine));
        }
        
        // Close Program class
        _output.AppendLine("}");
        
        return _output.ToString();
    }

    /// <summary>
    /// Translate use statement
    /// </summary>
    private void TranslateUseStatement(string line)
    {
        // use C#.Console.* -> using System; (already added)
        // use C#.System.* -> using System;
        // For now, skip C#.* imports as they're handled in header
        if (line.Contains("C#."))
        {
            // Already handled in header
            return;
        }
        
        // Other imports
        _output.AppendLine($"// {line}");
    }

    /// <summary>
    /// Translate class declaration
    /// </summary>
    private void TranslateClassDeclaration(string line)
    {
        // class Foo { -> public class Foo {
        var match = Regex.Match(line, @"class\s+(\w+)");
        if (match.Success)
        {
            var className = match.Groups[1].Value;
            
            // Get indentation from original line
            var indent = line.Substring(0, line.Length - line.TrimStart().Length);
            
            _output.AppendLine($"{indent}public class {className}");
            _output.AppendLine($"{indent}{{");
        }
        else
        {
            _output.AppendLine(line);
        }
    }

    /// <summary>
    /// Check if line is method declaration
    /// </summary>
    private bool IsMethodDeclaration(string line)
    {
        // void main() { or int foo(int x) {
        return Regex.IsMatch(line, @"^(void|int|float|double|string|bool)\s+\w+\s*\(");
    }

    /// <summary>
    /// Translate method declaration
    /// </summary>
    private void TranslateMethodDeclaration(string line)
    {
        // void main() { -> public static void Main() {
        var match = Regex.Match(line, @"^(void|int|float|double|string|bool)\s+(\w+)\s*\((.*?)\)");
        if (match.Success)
        {
            var returnType = TranslateType(match.Groups[1].Value);
            var methodName = match.Groups[2].Value;
            var parameters = match.Groups[3].Value;
            
            // Get indentation from original line
            var indent = line.Substring(0, line.Length - line.TrimStart().Length);
            
            // Special handling for main
            if (methodName.ToLower() == "main")
            {
                methodName = "Main";
                _hasMainMethod = true;
                // Main method should be indented 4 spaces (inside Program class)
                _output.AppendLine($"    public static {returnType} {methodName}({TranslateParameters(parameters)})");
            }
            else
            {
                _output.AppendLine($"{indent}public {returnType} {methodName}({TranslateParameters(parameters)})");
            }
            
            _output.AppendLine($"    {{");
            _currentMethodIndent = 8; // Method body should be 8 spaces (4 for class + 4 for method)
            _inMethod = true;
        }
        else
        {
            _output.AppendLine(line);
        }
    }

    /// <summary>
    /// Check if line is variable declaration
    /// </summary>
    private bool IsVariableDeclaration(string line)
    {
        // int x = 5; or string name;
        return Regex.IsMatch(line, @"^(int|float|double|string|bool)\s+\w+");
    }

    /// <summary>
    /// Translate variable declaration
    /// </summary>
    private void TranslateVariableDeclaration(string line)
    {
        // int x = 5; -> int x = 5;
        // string name; -> string name;
        var match = Regex.Match(line, @"^(int|float|double|string|bool)\s+(\w+)(.*)$");
        if (match.Success)
        {
            var type = TranslateType(match.Groups[1].Value);
            var name = match.Groups[2].Value;
            var rest = match.Groups[3].Value;
            
            // Use current method indent if inside a method, otherwise use line indent
            var indent = _inMethod && _currentMethodIndent > 0 
                ? new string(' ', _currentMethodIndent) 
                : line.Substring(0, line.Length - line.TrimStart().Length);
            
            _output.AppendLine($"{indent}{type} {name}{rest}");
        }
        else
        {
            _output.AppendLine(line);
        }
    }

    /// <summary>
    /// Translate if statement
    /// </summary>
    private void TranslateIfStatement(string line)
    {
        // if (x > 0) { -> if (x > 0) {
        _output.AppendLine(line);
    }

    /// <summary>
    /// Translate for statement
    /// </summary>
    private void TranslateForStatement(string line)
    {
        // for (int i = 0; i < 10; i++) { -> for (int i = 0; i < 10; i++) {
        _output.AppendLine(line);
    }

    /// <summary>
    /// Translate while statement
    /// </summary>
    private void TranslateWhileStatement(string line)
    {
        // while (x > 0) { -> while (x > 0) {
        _output.AppendLine(line);
    }

    /// <summary>
    /// Translate return statement
    /// </summary>
    private void TranslateReturnStatement(string line)
    {
        // return x; -> return x;
        _output.AppendLine(line);
    }

    /// <summary>
    /// Translate expression
    /// </summary>
    private string TranslateExpression(string expr)
    {
        // Translate Hust types to C# types
        expr = Regex.Replace(expr, @"\bint\b", "int");
        expr = Regex.Replace(expr, @"\bfloat\b", "float");
        expr = Regex.Replace(expr, @"\bdouble\b", "double");
        expr = Regex.Replace(expr, @"\bstring\b", "string");
        expr = Regex.Replace(expr, @"\bbool\b", "bool");
        
        // Translate Hust boolean literals
        expr = Regex.Replace(expr, @"\btrue\b", "true");
        expr = Regex.Replace(expr, @"\bfalse\b", "false");
        
        return expr;
    }

    /// <summary>
    /// Translate Hust type to C# type
    /// </summary>
    private string TranslateType(string hustType)
    {
        return hustType switch
        {
            "void" => "void",
            "int" => "int",
            "float" => "float",
            "double" => "double",
            "string" => "string",
            "bool" => "bool",
            _ => hustType
        };
    }

    /// <summary>
    /// Translate parameters
    /// </summary>
    private string TranslateParameters(string parameters)
    {
        if (string.IsNullOrWhiteSpace(parameters))
        {
            return "";
        }
        
        var parts = parameters.Split(',');
        var translated = new List<string>();
        
        foreach (var part in parts)
        {
            var trimmed = part.Trim();
            var match = Regex.Match(trimmed, @"^(int|float|double|string|bool)\s+(\w+)$");
            if (match.Success)
            {
                var type = TranslateType(match.Groups[1].Value);
                var name = match.Groups[2].Value;
                translated.Add($"{type} {name}");
            }
            else
            {
                translated.Add(trimmed);
            }
        }
        
        return string.Join(", ", translated);
    }

    /// <summary>
    /// Emit line with indentation from preprocessor
    /// </summary>
    private void EmitLine(string line)
    {
        if (string.IsNullOrWhiteSpace(line))
        {
            _output.AppendLine();
            return;
        }
        
        // Use the line as-is from preprocessor (already has correct indentation)
        _output.AppendLine(line);
    }
}
